async function createPgFixture({ runTrigger = true } = {}) {
  const pg = new PGlite()
  const setup = await readFile(new URL('../database/setup.sql', import.meta.url), 'utf8')
  const permissions = await readFile(new URL('../database/security_payment_profile_columns.sql', import.meta.url), 'utf8')
  const profilesSql = setup.slice(
    setup.indexOf('CREATE TABLE IF NOT EXISTS public.profiles'),
    setup.indexOf('CREATE TABLE IF NOT EXISTS public.class_groups')
  )
  const triggerSql = setup.slice(
    setup.indexOf('CREATE OR REPLACE FUNCTION public.handle_new_user()'),
    setup.indexOf('CREATE OR REPLACE FUNCTION public.update_updated_at_column()')
  )

  await pg.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth;
    GRANT USAGE ON SCHEMA public, auth TO anon, authenticated, service_role;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE
      AS $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    CREATE TABLE auth.users (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      email text UNIQUE NOT NULL,
      raw_user_meta_data jsonb DEFAULT '{}'::jsonb
    );
    CREATE TABLE public.companies (id bigint PRIMARY KEY);
    CREATE TABLE public.questions (id bigint PRIMARY KEY);
    CREATE TABLE public.user_responses (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
      question_id bigint REFERENCES public.questions(id) ON DELETE CASCADE NOT NULL,
      response text NOT NULL,
      questionnaire_type text NOT NULL,
      created_at timestamptz DEFAULT now()
    );
    INSERT INTO public.questions (id) VALUES (600), (601);
  `)
  await pg.exec(profilesSql)
  await pg.exec(`
    ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
    ${setup.match(/CREATE POLICY "Users can (?:view|insert|update) their own profile"[^;]+;/g).join('\n')}
    GRANT ALL ON public.user_responses, public.questions TO service_role;
  `)
  await pg.exec(permissions)
  if (runTrigger) {
    await pg.exec(triggerSql)
  }

  function tableApi(tableName) {
    const state = { filters: [], limitCount: null, action: 'select', payload: null }
    const builder = {
      select() {
        return builder
      },
      eq(column, value) {
        state.filters.push([column, value])
        return builder
      },
      limit(count) {
        state.limitCount = count
        return builder
      },
      async maybeSingle() {
        const { data, error } = await executeSelect()
        return { data: data?.[0] || null, error }
      },
      update(payload) {
        state.action = 'update'
        state.payload = payload
        return {
          async eq(column, value) {
            state.filters.push([column, value])
            return executeUpdate()
          }
        }
      },
      async upsert(payload) {
        const columns = Object.keys(payload)
        const values = Object.values(payload)
        const placeholders = columns.map((_, idx) => `$${idx + 1}`).join(', ')
        const assignments = columns
          .filter((col) => col !== 'id')
          .map((col) => `${col} = EXCLUDED.${col}`)
          .join(', ')
        try {
          await pg.query(
            `INSERT INTO public.${tableName} (${columns.join(', ')}) VALUES (${placeholders}) ON CONFLICT (id) DO UPDATE SET ${assignments}`,
            values
          )
          return { data: null, error: null }
        } catch (error) {
          return { data: null, error }
        }
      },
      async insert(rows) {
        const list = Array.isArray(rows) ? rows : [rows]
        try {
          for (const row of list) {
            const columns = Object.keys(row)
            const values = Object.values(row)
            const placeholders = columns.map((_, idx) => `$${idx + 1}`).join(', ')
            await pg.query(
              `INSERT INTO public.${tableName} (${columns.join(', ')}) VALUES (${placeholders})`,
              values
            )
          }
          return { data: null, error: null }
        } catch (error) {
          return { data: null, error }
        }
      },
      then(resolve, reject) {
        return executeSelect().then(resolve, reject)
      }
    }

    async function executeSelect() {
      try {
        const params = []
        const where = state.filters.map(([col, val]) => {
          params.push(val)
          return `${col} = $${params.length}`
        })
        const whereSql = where.length ? `WHERE ${where.join(' AND ')}` : ''
        const limitSql = state.limitCount ? `LIMIT ${Number(state.limitCount)}` : ''
        const res = await pg.query(`SELECT * FROM public.${tableName} ${whereSql} ${limitSql}`, params)
        return { data: res.rows, error: null }
      } catch (error) {
        return { data: null, error }
      }
    }

    async function executeUpdate() {
      try {
        const entries = Object.entries(state.payload || {})
        const params = entries.map(([, val]) => val)
        const sets = entries.map(([col], idx) => `${col} = $${idx + 1}`).join(', ')
        const where = state.filters.map(([col, val]) => {
          params.push(val)
          return `${col} = $${params.length}`
        })
        await pg.query(`UPDATE public.${tableName} SET ${sets} WHERE ${where.join(' AND ')}`, params)
        return { data: null, error: null }
      } catch (error) {
        return { data: null, error }
      }
    }

    return builder
  }

  const createdUsers = []
  const supabaseAdmin = {
    from: tableApi,
    auth: {
      admin: {
        async createUser({ email, user_metadata }) {
          const inserted = await pg.query(
            'INSERT INTO auth.users (email, raw_user_meta_data) VALUES ($1, $2::jsonb) RETURNING id, email, raw_user_meta_data',
            [email, JSON.stringify(user_metadata || {})]
          )
          const row = inserted.rows[0]
          const user = { id: row.id, email: row.email, user_metadata: row.raw_user_meta_data }
          createdUsers.push(user)
          return { data: { user }, error: null }
        }
      }
    }
  }

  const app = express()
  app.use(express.json())
  app.post('/api/auth/register', createRegisterHandler({ supabase: supabaseAdmin, supabaseAdmin }))
  const server = app.listen(0, '127.0.0.1')
  await once(server, 'listening')
  const baseUrl = `http://127.0.0.1:${server.address().port}`

  return {
    pg,
    createdUsers,
    baseUrl,
    async close() {
      await new Promise((resolve) => server.close(resolve))
      await pg.close()
    }
  }
}

test('phone normalization and optional validation handle empty, French, international and invalid inputs', () => {
  assert.equal(normalizePhoneNumber(''), '')
  assert.equal(normalizePhoneNumber('   '), '')
  assert.equal(normalizePhoneNumber('\u202A+33\u00A06\u00A012\u00A034\u00A056\u00A078\u202C'), '+33 6 12 34 56 78')
  assert.equal(isValidOptionalPhoneNumber(''), true)
  assert.equal(isValidOptionalPhoneNumber('06 12 34 56 78'), true)
  assert.equal(isValidOptionalPhoneNumber('+41 79 123 45 67'), true)
  assert.equal(isValidOptionalPhoneNumber('abc'), false)
  assert.equal(isValidOptionalPhoneNumber('12345'), false)
})

test('user registration persists optional phone_number in profiles via DB trigger, allows empty phone, and grants authenticated updates', async () => {
  const fixture = await createPgFixture({ runTrigger: true })
  try {
    // 1. Register WITH phone number
    const withPhoneRes = await fetch(`${fixture.baseUrl}/api/auth/register`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'with-phone@example.com',
        password: 'password123',
        userData: {
          first_name: 'Camille',
          last_name: 'Martin',
          gender: 'Femme',
          department: '75',
          phone_number: ' \u202A+33\u00A06\u00A012\u00A034\u00A056\u00A078\u202C '
        },
        questionnaireResponses: [{ question_id: 600, answer: 'Carrément' }]
      })
    })
    assert.equal(withPhoneRes.status, 201)
    const withPhoneBody = await withPhoneRes.json()
    const userWithPhoneId = withPhoneBody.user.id
    assert.equal(fixture.createdUsers[0].user_metadata.phone_number, '+33 6 12 34 56 78')

    const profileWithPhone = (await fixture.pg.query(
      'SELECT first_name, last_name, department, phone_number FROM public.profiles WHERE id = $1',
      [userWithPhoneId]
    )).rows[0]
    assert.deepEqual(profileWithPhone, {
      first_name: 'Camille',
      last_name: 'Martin',
      department: '75',
      phone_number: '+33 6 12 34 56 78'
    })

    // 2. Register WITHOUT phone number (optional)
    const withoutPhoneRes = await fetch(`${fixture.baseUrl}/api/auth/register`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'without-phone@example.com',
        password: 'password123',
        userData: {
          first_name: 'Alex',
          last_name: 'Dupont',
          gender: 'Homme',
          department: '69'
        }
      })
    })
    assert.equal(withoutPhoneRes.status, 201)
    const withoutPhoneBody = await withoutPhoneRes.json()
    const userWithoutPhoneId = withoutPhoneBody.user.id
    assert.equal(fixture.createdUsers[1].user_metadata.phone_number, '')

    const profileWithoutPhone = (await fixture.pg.query(
      'SELECT first_name, phone_number FROM public.profiles WHERE id = $1',
      [userWithoutPhoneId]
    )).rows[0]
    assert.deepEqual(profileWithoutPhone, {
      first_name: 'Alex',
      phone_number: ''
    })

    // Verify authenticated RLS & column-level GRANTs allow updating phone_number to null or a number
    await fixture.pg.query("SELECT set_config('request.jwt.claim.sub', $1, false)", [userWithoutPhoneId])
    await fixture.pg.exec('SET ROLE authenticated')
    await fixture.pg.query('UPDATE public.profiles SET phone_number = NULL WHERE id = $1', [userWithoutPhoneId])
    assert.equal(
      (await fixture.pg.query('SELECT phone_number FROM public.profiles WHERE id = $1', [userWithoutPhoneId])).rows[0].phone_number,
      null
    )
    await fixture.pg.query("UPDATE public.profiles SET phone_number = '06 99 88 77 66' WHERE id = $1", [userWithoutPhoneId])
    assert.equal(
      (await fixture.pg.query('SELECT phone_number FROM public.profiles WHERE id = $1', [userWithoutPhoneId])).rows[0].phone_number,
      '06 99 88 77 66'
    )
    await fixture.pg.exec('RESET ROLE')

    // 3. Reject malformed non-empty phone number without creating an account
    const invalidPhoneRes = await fetch(`${fixture.baseUrl}/api/auth/register`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'invalid-phone@example.com',
        password: 'password123',
        userData: {
          first_name: 'Lou',
          last_name: 'Bernard',
          gender: 'Autre',
          department: '33',
          phone_number: 'pas-un-numero'
        }
      })
    })
    assert.equal(invalidPhoneRes.status, 400)
    assert.equal(fixture.createdUsers.length, 2)
  } finally {
    await fixture.close()
  }
})

test('user registration fallback stores phone_number when DB trigger did not create profile', async () => {
  const fixture = await createPgFixture({ runTrigger: false })
  try {
    const res = await fetch(`${fixture.baseUrl}/api/auth/register`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'fallback-phone@example.com',
        password: 'password123',
        userData: {
          first_name: 'Inès',
          last_name: 'Moreau',
          gender: 'Femme',
          department: '44',
          phone_number: '06 11 22 33 44'
        }
      })
    })
    assert.equal(res.status, 201)
    const { user } = await res.json()
    const profile = (await fixture.pg.query(
      'SELECT first_name, department, phone_number FROM public.profiles WHERE id = $1',
      [user.id]
    )).rows[0]
    assert.deepEqual(profile, {
      first_name: 'Inès',
      department: '44',
      phone_number: '06 11 22 33 44'
    })
  } finally {
    await fixture.close()
  }
})
