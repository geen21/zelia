import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'
import { PGlite } from '@electric-sql/pglite'
import { csvCell, filtersFor, pageFor, redactLead, requireVerifiedMfa } from '../utils/schoolDashboard.js'

const student = '11111111-1111-4111-8111-111111111111'
const owner = '22222222-2222-4222-8222-222222222222'
const partner = '33333333-3333-4333-8333-333333333333'

test('dashboard SQL: consent, attribution, isolation, exact totals and replay', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth; CREATE SCHEMA extensions;
      CREATE FUNCTION public.unaccent(text) RETURNS text LANGUAGE sql IMMUTABLE AS $$ SELECT $1 $$;
      CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,raw_user_meta_data jsonb DEFAULT '{}');
      CREATE TABLE public.companies(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text,owner_id uuid,email text,contact_first_name text,contact_last_name text);
      CREATE TABLE public.school_registration_requests(id bigint PRIMARY KEY,email text);
      CREATE TABLE public.profiles(id uuid PRIMARY KEY,first_name text,last_name text,gender text,age int,department text,contact_preference boolean);
      CREATE TABLE public.formation_france(id bigint PRIMARY KEY,etab_nom text,nmc text,commune text,etab_url text,fiche text);
      CREATE TABLE public.ecoles_partenaires(id uuid PRIMARY KEY,school_name text,formation_name text,city text,link text,is_active boolean,show_in_results boolean);
      CREATE TABLE public.informations_complementaires(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,user_id uuid,
        question_id text,question_text text,answer_text text,created_at timestamptz DEFAULT now());
      CREATE TABLE public.formation_info_requests(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,user_id uuid,formation_source text,
        formation_ref text,created_at timestamptz DEFAULT now(),email text,first_name text,last_name text);
      CREATE TABLE public.contact_submitted(id uuid DEFAULT gen_random_uuid(),user_id uuid,formation_id uuid,submitted_at timestamptz DEFAULT now());
      CREATE TABLE public.school_portal_members(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,company_id bigint,user_id uuid,role text,UNIQUE(company_id,user_id));
      CREATE TABLE public.school_lead_status(company_id bigint,lead_key text,status text DEFAULT 'nouveau',note text,notified_at timestamptz,updated_at timestamptz DEFAULT now(),UNIQUE(company_id,lead_key));
      CREATE TABLE public.school_lead_reveals(company_id bigint,lead_key text,revealed_at timestamptz DEFAULT now());
      INSERT INTO auth.users(id,email) VALUES('${student}','student@example.com'),('${owner}','owner@example.com');
      INSERT INTO public.profiles VALUES('${student}','Camille','Martin','',17,'75',false);
      INSERT INTO public.companies(id,name,email) VALUES(1,'School','school@example.com'),(2,'Homonym School','other-school@example.com');
      INSERT INTO public.formation_france VALUES(9007199254740993,'School','Bachelor national','Paris','https://school.example',NULL);
      INSERT INTO public.ecoles_partenaires VALUES('${partner}','School','Bachelor partenaire','Lyon','https://school.example',true,true);
    `)
    const migration = await readFile(new URL('../database/migration_partner_dashboards.sql', import.meta.url), 'utf8')
    await db.exec(migration)
    await db.exec(migration)
    await db.query(`INSERT INTO school_catalog_links(company_id,source,formation_ref,campus,validated_by)
      VALUES(1,'formation_france','9007199254740993','Paris',$1),(1,'ecoles_partenaires',$2,'Lyon',$1)`, [owner, partner])
    const selection = (request, version) => JSON.stringify([
      { type: 'formation', sourceTable: 'formation_france', rawId: '9007199254740993', requestMoreInformation: request, sharingVersion: version }
    ])
    const save = (text) => db.query('SELECT school_save_selection($1,$2,$3)', [student, text, 'Selection'])
    const dashboard = async (company = 1, filters = {}, limit = 50, offset = 0) =>
      (await db.query('SELECT school_dashboard($1,$2,$3,$4) result', [company, JSON.stringify(filters), limit, offset])).rows[0].result
    await save(selection(false))
    assert.equal((await dashboard()).total, 0, 'display is not consent')
    await save(selection('true'))
    assert.equal((await dashboard()).total, 0, 'string booleans are not consent')
    await save('malformed')
    assert.equal((await dashboard()).total, 0)
    await save(selection(true))
    let result = await dashboard()
    assert.equal(result.total, 1)
    assert.equal(result.leads[0].origin, 'natural')
    assert.equal(result.leads[0].detailedAllowed, false, 'historical request does not allow detailed responses')
    assert.equal((await dashboard(2)).total, 0, 'homonym has no access')
    await db.query('INSERT INTO contact_submitted(user_id,formation_id) VALUES($1,$2)', [student, partner])
    result = await dashboard()
    assert.equal(result.total, 1)
    assert.deepEqual(result.byOrigin, { natural: 0, sponsored: 0, mixed: 1, unknown: 0 })
    assert.equal((await dashboard(1, { origin: 'natural' })).total, 1)
    assert.equal((await dashboard(1, { campus: 'Lyon' })).total, 1)
    await db.exec("DELETE FROM school_catalog_links WHERE source='formation_france'")
    await db.query("INSERT INTO school_catalog_links(company_id,source,formation_ref,validated_by) VALUES(2,'formation_france','9007199254740993',$1)", [owner])
    assert.equal((await dashboard(2)).total, 0, 'moving a catalogue mapping must not transfer historical consent')
    await db.exec("DELETE FROM school_catalog_links WHERE source='formation_france'")
    await db.query("INSERT INTO school_catalog_links(company_id,source,formation_ref,campus,validated_by) VALUES(1,'formation_france','9007199254740993','Paris',$1)", [owner])
    await db.query('SELECT school_set_sharing($1,true)', [student])
    assert.equal((await dashboard()).leads[0].detailedAllowed, true)
    const grantedAt = (await db.query('SELECT granted_at FROM school_sharing_consents WHERE user_id=$1', [student])).rows[0].granted_at
    await db.query('SELECT school_set_sharing($1,false)', [student])
    assert.deepEqual((await db.query('SELECT granted_at FROM school_sharing_consents WHERE user_id=$1', [student])).rows[0].granted_at, grantedAt)
    assert.equal((await dashboard()).leads[0].detailedAllowed, false)
    await db.query('INSERT INTO school_sharing_blocks(user_id,company_id) VALUES($1,1)', [student])
    assert.equal((await dashboard()).total, 0)
    await db.exec('DELETE FROM school_sharing_blocks')
    await save(selection(true, 'orientation-dossier-v1'))
    assert.equal((await dashboard()).leads[0].detailedAllowed, true)
    await db.exec(`
      INSERT INTO formation_info_requests(formation_source,formation_ref,email,first_name)
        SELECT 'formation_france','9007199254740993','guest-'||n||'@example.com','Guest' FROM generate_series(1,5010) n;
    `)
    result = await dashboard()
    assert.equal(result.total, 5011)
    assert.equal(result.leads.length, 50)
    assert.equal((await dashboard(1, {}, 1000, 5000)).leads.length, 11)
    const exported = await dashboard(1, {}, -1)
    assert.equal(exported.leads.length, exported.total)
    assert.equal(new Set(exported.leads.map((lead) => lead.leadKey)).size, 5011)
    assert.equal(Object.values(result.byOrigin).reduce((a, b) => a + b, 0), result.total)
    await db.exec("DELETE FROM school_portal_events WHERE event_key='request:1'")
    await db.exec(migration)
    assert.equal((await dashboard()).total, 5010, 'replaying a migration must not resurrect deleted events')
    assert.equal((await dashboard(1, { from: '2099-01-01' })).total, 0)
    await db.exec(`SET ROLE authenticated`)
    await assert.rejects(db.query('SELECT * FROM school_portal_events'), /permission denied/)
    await assert.rejects(db.query('SELECT school_dashboard(1)'), /permission denied/)
    await db.exec('RESET ROLE')
    await db.query('SELECT school_attach_account(1,$1,$2)', [owner, 'owner'])
    await assert.rejects(db.query('SELECT school_attach_account(2,$1,$2)', [owner, 'member']), /SCHOOL_ACCOUNT_ALREADY_ATTACHED/)
    assert.equal((await db.query('SELECT school_claim_notification(1,$1) claimed', [`user:${student}`])).rows[0].claimed, true)
    assert.equal((await db.query('SELECT school_claim_notification(1,$1) claimed', [`user:${student}`])).rows[0].claimed, false)
    assert.equal((await db.query("SELECT school_claim_invitation(1,'invite@example.com','owner') claimed")).rows[0].claimed, true)
    assert.equal((await db.query("SELECT school_claim_invitation(1,'invite@example.com','owner') claimed")).rows[0].claimed, false)
    await db.exec("UPDATE school_portal_invitations SET status='failed'")
    assert.equal((await db.query("SELECT school_claim_invitation(1,'invite@example.com','owner') claimed")).rows[0].claimed, true)
    await db.exec("SELECT setval('companies_id_seq',2); INSERT INTO school_registration_requests VALUES(5,'new@example.com',NULL)")
    const created = (await db.query("SELECT school_create_portal('New school','new@example.com','Camille','Martin',5) item")).rows[0].item
    assert.equal(created.id, '3')
    assert.equal((await db.query('SELECT company_id FROM school_registration_requests WHERE id=5')).rows[0].company_id, 3)
    await assert.rejects(db.query("SELECT school_create_portal('New school','new@example.com','','',5)"), /REGISTRATION_ALREADY_LINKED/)
    await db.query("SELECT school_patch_lead(1,$1,'contacte',NULL)", [`user:${student}`])
    const noteUpdate = (await db.query("SELECT school_patch_lead(1,$1,NULL,'A rappeler') item", [`user:${student}`])).rows[0].item
    assert.deepEqual(noteUpdate, { status: 'contacte', note: 'A rappeler' })

    const mds = '55555555-5555-4555-8555-555555555555'
    const secondCampus = '66666666-6666-4666-8666-666666666666'
    const mdsOwner = '77777777-7777-4777-8777-777777777777'
    await db.query(`INSERT INTO ecoles_partenaires(id,school_name,formation_name,city,is_active,show_in_results)
      VALUES($1,'MyDigitalSchool','Bachelor informatique','Paris',true,true)`, [mds])
    await db.query('INSERT INTO contact_submitted(user_id,formation_id) VALUES($1,$2)', [student, mds])
    await db.exec(`INSERT INTO ecoles_partenaires(id,school_name,formation_name,city,is_active,show_in_results)
      VALUES('88888888-8888-4888-8888-888888888888','Ancien partenaire','Formation archivee','Nantes',false,false);
      INSERT INTO ecoles_partenaires(id,school_name,formation_name,city,is_active,show_in_results)
      SELECT md5('auto-portal-fixture-'||n)::uuid,'Partenaire volume','Formation '||n,'Campus '||n,true,true
      FROM generate_series(1,1001) n;`)
    await db.exec('ALTER TABLE school_registration_requests ADD COLUMN school_name text')
    const autoMigration = await readFile(new URL('../database/migration_partner_dashboards_auto_spaces.sql', import.meta.url), 'utf8')
    const authCount = (await db.query('SELECT count(*)::int count FROM auth.users')).rows[0].count
    await db.exec(autoMigration)
    const mdsCompany = (await db.query('SELECT portal_company_id FROM ecoles_partenaires WHERE id=$1', [mds])).rows[0].portal_company_id
    assert.ok(mdsCompany)
    assert.equal((await db.query('SELECT portal_company_id FROM ecoles_partenaires WHERE id=$1', [partner])).rows[0].portal_company_id, 1, 'reuse an existing school and its ownership')
    assert.equal((await db.query('SELECT owner_id FROM companies WHERE id=1')).rows[0].owner_id, owner)
    assert.ok((await db.query("SELECT portal_company_id FROM ecoles_partenaires WHERE is_active=false")).rows[0].portal_company_id, 'archived partners retain a dashboard')
    const bulk = (await db.query("SELECT count(*)::int formations,count(DISTINCT portal_company_id)::int spaces FROM ecoles_partenaires WHERE school_name='Partenaire volume'")).rows[0]
    assert.deepEqual(bulk, { formations: 1001, spaces: 1 })
    assert.equal((await db.query('SELECT email FROM companies WHERE id=$1', [mdsCompany])).rows[0].email, null, 'never invent a contact email')
    assert.equal((await db.query('SELECT count(*)::int count FROM auth.users')).rows[0].count, authCount, 'creating dashboards does not create Auth users')
    assert.equal((await dashboard(mdsCompany)).total, 1, 'existing consenting partner requests become visible')
    assert.equal((await dashboard(mdsCompany)).leads[0].detailedAllowed, false, 'automatic dashboards do not extend historical consent')
    await db.query("INSERT INTO school_registration_requests(id,email,school_name) VALUES(6,'responsable@mds.example','MyDigitalSchool')")
    assert.equal((await db.query('SELECT company_id FROM school_registration_requests WHERE id=6')).rows[0].company_id, mdsCompany)
    assert.equal((await db.query('SELECT count(*)::int count FROM auth.users')).rows[0].count, authCount)
    await db.query(`INSERT INTO ecoles_partenaires(id,school_name,formation_name,city,is_active,show_in_results)
      VALUES($1,'  mydigitalschool  ','Bachelor marketing','Lyon',true,true)`, [secondCampus])
    assert.equal((await db.query('SELECT portal_company_id FROM ecoles_partenaires WHERE id=$1', [secondCampus])).rows[0].portal_company_id, mdsCompany, 'all campuses share one dashboard')
    const links = (await db.query("SELECT company_id,validated_by,link_origin FROM school_catalog_links WHERE formation_ref IN ($1,$2)", [mds, secondCampus])).rows
    assert.equal(links.length, 2)
    assert.ok(links.every((link) => link.company_id === mdsCompany && link.validated_by === null && link.link_origin === 'partner'))
    await assert.rejects(db.query("DELETE FROM school_catalog_links WHERE source='ecoles_partenaires' AND formation_ref=$1", [mds]), /PARTNER_PORTAL_LINK_REQUIRED/)
    await assert.rejects(db.query("UPDATE ecoles_partenaires SET school_name='Unrelated school' WHERE id=$1", [mds]), /PARTNER_SCHOOL_CHANGE_REQUIRES_REVIEW/)
    await db.query("UPDATE ecoles_partenaires SET city='Bordeaux' WHERE id=$1", [secondCampus])
    assert.equal((await db.query("SELECT campus FROM school_catalog_links WHERE source='ecoles_partenaires' AND formation_ref=$1", [secondCampus])).rows[0].campus, 'Bordeaux')
    await assert.rejects(db.query("INSERT INTO companies(name,email) VALUES('Non partner',NULL)"), /company_contact_or_partner_portal_check/)
    await assert.rejects(db.query("SELECT school_create_portal('MyDigitalSchool','duplicate@example.com','','',NULL)"), /PARTNER_PORTAL_ALREADY_EXISTS/)
    await db.query("INSERT INTO auth.users(id,email) VALUES($1,'contact@mds.example')", [mdsOwner])
    await db.query("SELECT school_attach_account($1,$2,'owner')", [mdsCompany, mdsOwner])
    assert.equal((await db.query('SELECT email FROM companies WHERE id=$1', [mdsCompany])).rows[0].email, 'contact@mds.example')
    await db.exec(autoMigration)
    assert.equal((await db.query('SELECT portal_company_id FROM ecoles_partenaires WHERE id=$1', [mds])).rows[0].portal_company_id, mdsCompany)
    assert.equal((await db.query('SELECT owner_id FROM companies WHERE id=$1', [mdsCompany])).rows[0].owner_id, mdsOwner)
    assert.equal((await db.query('SELECT count(*)::int count FROM ecoles_partenaires WHERE portal_company_id IS NULL')).rows[0].count, 0)
    await db.exec('SET ROLE authenticated')
    await assert.rejects(db.query("SELECT ensure_partner_portal('Forbidden')"), /permission denied/)
    await db.exec('RESET ROLE')
  } finally { await db.close() }
})

test('filters, redaction, CSV and verified MFA', () => {
  assert.throws(() => filtersFor({ origin: 'invalid' }))
  assert.throws(() => pageFor({ offset: -1 }))
  assert.throws(() => pageFor({ limit: 1001 }))
  assert.equal(csvCell('=HYPERLINK("bad")'), `"'=HYPERLINK(""bad"")"`)
  const lead = { email: 'student@example.com', nom: 'Martin', revealed: false }
  assert.equal(redactLead(lead).email, '***@***')
  assert.equal(redactLead(lead, true).email, lead.email)
  const req = { user: { factors: [{ status: 'verified' }] }, headers: { authorization: `Bearer header.${Buffer.from('{"aal":"aal1"}').toString('base64url')}.signature` } }
  assert.throws(() => requireVerifiedMfa(req), /MFA_REQUIRED/)
  req.headers.authorization = `Bearer header.${Buffer.from('{"aal":"aal2"}').toString('base64url')}.signature`
  assert.doesNotThrow(() => requireVerifiedMfa(req))
})
